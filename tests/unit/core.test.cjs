require('./register.cjs');
const {test} = require('node:test');
const assert = require('node:assert/strict');
const {isISODate} = require('../../src/lib/utils/date.ts');
const {isImageUrl} = require('../../src/lib/utils/image-url.ts');
const {normalizeIndianMobile} = require('../../src/lib/utils/phone.ts');
const {formatPriceShort, formatAvailability} = require('../../src/lib/utils/format.ts');
const {totalRupees} = require('../../src/lib/utils/price.ts');
const {enquirySchema, sellRequestSchema} = require('../../src/lib/validations/lead.ts');
const {propertySchema} = require('../../src/lib/validations/property.ts');
const {parseListingParams} = require('../../src/lib/listing-params.ts');
const {MOCK_PROPERTIES} = require('../../src/lib/data/mockProperties.ts');
const good = {...MOCK_PROPERTIES[0], id: undefined};
const lead = {name:'Test User',phone:'+91 98765 43210',email:'',message:'Please call',website:''};
test('valid leap day',()=>assert.equal(isISODate('2028-02-29'),true));
test('invalid calendar day rejected',()=>assert.equal(isISODate('2026-02-31'),false));
test('date injection rejected',()=>assert.equal(isISODate('2026-11-01abc'),false));
test('normalizes Indian country prefix',()=>assert.equal(normalizeIndianMobile('+91 98765 43210'),'9876543210'));
test('rejects invalid mobile',()=>assert.equal(normalizeIndianMobile('123'),null));
test('valid enquiry',()=>assert.equal(enquirySchema.safeParse(lead).success,true));
test('honeypot rejected by schema',()=>assert.equal(enquirySchema.safeParse({...lead,website:'spam'}).success,false));
test('impossible visit date rejected',()=>assert.equal(enquirySchema.safeParse({...lead,visit_date:'2026-02-31'}).success,false));
test('owner form validation',()=>assert.equal(sellRequestSchema.safeParse({owner_name:'Test Owner',phone:'9876543210',intention:'sell',property_type:'2BHK',locality:'Virar'}).success,true));
test('valid demo property schema',()=>assert.equal(propertySchema.safeParse(good).success,true));
test('zero area rejected',()=>assert.equal(propertySchema.safeParse({...good,area_sqft:0}).success,false));
test('no photos cannot publish',()=>assert.equal(propertySchema.safeParse({...good,images:[],status:'published'}).success,false));
test('floor cannot exceed building height',()=>assert.equal(propertySchema.safeParse({...good,floor:20,total_floors:4}).success,false));
test('rental cannot become sold',()=>assert.equal(propertySchema.safeParse({...good,purpose:'rent',status:'sold'}).success,false));
test('invalid availability rejected',()=>assert.equal(propertySchema.safeParse({...good,available_from:'tomorrow'}).success,false));
test('unknown remote image host rejected',()=>assert.equal(isImageUrl('https://unknown.example/photo.jpg'),false));
test('insecure remote photo rejected',()=>assert.equal(isImageUrl('http://images.unsplash.com/test'),false));
test('known remote photo accepted',()=>assert.equal(isImageUrl('https://images.unsplash.com/photo-test'),true));
test('local photo accepted',()=>assert.equal(isImageUrl('/doors/interior.webp'),true));
test('rent price suffix occurs once',()=>assert.deepEqual(formatPriceShort(16500,'per_month'),{amount:'₹16,500',suffix:'/ month'}));
test('crores normalized for budget comparisons',()=>assert.equal(totalRupees(1.2,'crores',null),12000000));
test('lacs normalized',()=>assert.equal(totalRupees(45,'lacs',null),4500000));
test('per-square-foot unknown area cannot imply a total',()=>assert.equal(totalRupees(9000,'per_sqft',null),null));
test('per-square-foot total',()=>assert.equal(totalRupees(9000,'per_sqft',700),6300000));
test('query parser rejects unknown values',()=>{const p=parseListingParams('rent',{type:'bad',furnish:'invalid',page:'-9',sort:'nonsense'});assert.equal(p.page,1);assert.equal(p.sort,'newest');assert.equal(p.filters.category,undefined)});
test('availability uses India date',()=>assert.equal(formatAvailability('2026-11-06',new Date('2026-11-06T10:00:00Z')),'Available now'));
test('sale cannot use monthly rent',()=>assert.equal(propertySchema.safeParse({...good,purpose:'buy',price_unit:'per_month'}).success,false));
test('commercial rent cannot use a lump-sum lacs unit',()=>assert.equal(propertySchema.safeParse({...good,purpose:'rent',category:'commercial',price_unit:'lacs'}).success,false));
